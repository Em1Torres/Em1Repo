
#include <iostream>
using namespace std;

class Calculadora {
private:
    float resultado;
public:
    void sumar(float a, float b) {
        resultado = a + b;
        cout << resultado;
        return;
    }
    void restar(float a, float b) {
        resultado = a - b;
        cout << resultado;
        return;
    }
};

int main() {
    const int limite = 1000;
    float suma = 0.0;
    int contador = 0;
    for (int i = 0; i < limite; i = i + 1) {
        if (true) {
            suma = suma + i;
            contador = contador + 1;
        } else {
            continue;
        }
    }
    while (contador > 0) {
        switch (contador) {
            case 1:
                cout << "uno";
                break;
            case 2:
                cout << "dos";
                break;
            default:
                break;
        }
        contador = contador - 1;
    }
    cout << suma;
    return 0;
}

